# Vertices visualization function
def plot_vertices_3d(side_vertices):
    x, y, z = side_vertices[:, 0], side_vertices[:, 1], side_vertices[:, 2]

    fig = plt.figure()
    ax = fig.add_subplot(111, projection='3d')
    ax.scatter(x, y, z)

    # Add vertex index to each point
    for i in range(len(side_vertices)):
        ax.text(x[i], y[i], z[i], str(i))

    plt.show()

# Build a numpy-stl Mesh from a set of vertices/faces
def build_mesh(vertices, faces):
    m = mesh.Mesh(np.zeros(faces.shape[0], dtype=mesh.Mesh.dtype))

    for i, f in enumerate(faces):
        for j in range(3):
            m.vectors[i][j] = vertices[f[j], :]

    return m

# Mesh STL file generating function
def save_stl(side_vertices, side_faces, filename):
    build_mesh(side_vertices, side_faces).save(filename)

    # Overwrite STL file timestamp so that same inputs produces a byte-identical file
    with open(filename, 'r+b') as f:
        f.write('Generated by robogami_description/generate_robot_description.py'.ljust(80)[:80].encode('ascii'))

# Compute mesh inertial properties
def compute_mass_properties(vertices, faces, density):
    volume, cog, inertia = build_mesh(vertices, faces).get_mass_properties()
    return volume * density, cog, inertia * density

# Add point mass representing motors
def add_point_mass(mass, cog, inertia, extra_mass, extra_pos):
    cog = np.asarray(cog, dtype=float)
    extra_pos = np.asarray(extra_pos, dtype=float)
    total_mass = mass + extra_mass

    if total_mass == 0:
        return total_mass, np.zeros(3), inertia

    total_cog = (mass * cog + extra_mass * extra_pos) / total_mass

    def parallel_axis_shift(point_mass, point):
        d = point - total_cog
        return point_mass * (np.dot(d, d) * np.eye(3) - np.outer(d, d))

    total_inertia = inertia + parallel_axis_shift(mass, cog) + parallel_axis_shift(extra_mass, extra_pos)
    return total_mass, total_cog, total_inertia

