# Link materials genersting function (for visualization/debugging)
def generate_urdf_material_color(name, rgbs):
    r, g, b, a = rgbs

    return "\n".join([
        f'\t<material name="{name}">',
        f'\t\t<color rgba="{r} {g} {b} {a}"/>',
        '\t</material>\n'
    ])

# Link URDF string generating function
def generate_link_urdf_str(link_name, mesh_name, mass, cog, inertia, offset=0):
    cog_x, cog_y, cog_z = cog[0] + offset, cog[1], cog[2]
    ixx, ixy, ixz = inertia[0, 0], inertia[0, 1], inertia[0, 2]
    iyy, iyz = inertia[1, 1], inertia[1, 2]
    izz = inertia[2, 2]

    return "\n".join([
        '\t<link name="{}">'.format(link_name),
        '\t\t<inertial>',
        '\t\t\t<mass value="{}" />'.format(mass),
        '\t\t\t<origin rpy="0 0 0" xyz="{} {} {}"/>'.format(cog_x, cog_y, cog_z),
        '\t\t\t<inertia ixx="{}" ixy="{}" ixz="{}" iyy="{}" iyz="{}" izz="{}"/>'.format(ixx, ixy, ixz, iyy, iyz, izz),
        '\t\t</inertial>',
        '\t\t<visual>',
        '\t\t\t<origin rpy="0 0 0" xyz="{} 0 0"/>'.format(str(offset)),
        '\t\t\t<geometry>',
        '\t\t\t\t<mesh filename="package://robogami_description/meshes/{}.stl"/>'.format(mesh_name),
        '\t\t\t</geometry>',
        '\t\t\t<material name="Gray"/>',
        '\t\t</visual>',
        '\t</link>\n\n'
    ])
    
# Joint URDF string generating function
def generate_joint_urdf_str(joint_name, parent_link, child_link, ll, ul, axis, rpy, xyz):
    return "\n".join([
        '\t<joint name="{}" type="revolute">'.format(joint_name),
        '\t\t<parent link="{}"/>'.format(parent_link),
        '\t\t<child link="{}"/>'.format(child_link),
        '\t\t<axis xyz="{}"/>'.format(axis),
        '\t\t<limit effort="1" lower="{}" upper="{}" velocity="1"/>'.format(str(ll), str(ul)), # TODO double check joint limits
        '\t\t<origin rpy="{} {} {}" xyz="{} {} {}"/>'.format(*rpy, *xyz),
        '\t</joint>\n\n'
    ])

# Spherical joint URDF string generating function
def generate_spherical_joint_urdf_str(parent_link, child_link, extra_link1, extra_link2, extra_joint1, extra_joint2, extra_joint3):
    return "\n".join([
        '\t<link name="{}"/>\n'.format(extra_link1), # two virtual links
        '\t<link name="{}"/>\n'.format(extra_link2),
        '\t<joint name="{}" type="revolute">'.format(extra_joint1), # X rotation joint
        '\t\t<parent link="{}"/>'.format(parent_link),
        '\t\t<child link="{}"/>'.format(extra_link1),
        '\t\t<axis xyz="1 0 0"/>',
        '\t\t<limit effort="1" lower="-1.56" upper="1.56" velocity="1"/>',
        '\t\t<origin rpy="0 {} 0" xyz="{} 0 0"/>'.format(radians(180), -side_H),
        '\t</joint>\n',
        '\t<joint name="{}" type="revolute">'.format(extra_joint2), # Y rotation joint
        '\t\t<parent link="{}"/>'.format(extra_link1),
        '\t\t<child link="{}"/>'.format(extra_link2),
        '\t\t<axis xyz="0 1 0"/>',
        '\t\t<limit effort="1" lower="0.1" upper="3.13" velocity="1"/>',
        '\t\t<origin rpy="0 0 0" xyz="0 0 0"/>',
        '\t</joint>\n',
        '\t<joint name="{}" type="revolute">'.format(extra_joint3), # Z ?? rotation joint
        '\t\t<parent link="{}"/>'.format(extra_link2),
        '\t\t<child link="{}"/>'.format(child_link),
        '\t\t<axis xyz="1 0 0"/>',
        '\t\t<limit effort="1" lower="-1.56" upper="1.56" velocity="1"/>',
        '\t\t<origin rpy="0 0 0" xyz="0 0 0"/>',
        '\t</joint>\n\n'
    ])

# Corner collision links generating function
def generate_corner_collision_links(link_name, parent_link, joint_origin, material):
    return "\n".join([
        '\t<link name="{}">'.format(link_name),
        '\t\t<visual>',
        '\t\t\t<geometry>',
        '\t\t\t\t<sphere radius="0.001"/>',
        '\t\t\t</geometry>\n',
        '\t\t\t<material name="{}"/>'.format(material),
        '\t\t</visual>',
        '\t\t<collision>',
        '\t\t\t<geometry>',
        '\t\t\t\t<sphere radius="0.001"/>',
        '\t\t\t</geometry>',
        '\t\t</collision>',
        '\t</link>',
        '\n\t<joint name="{}" type="fixed">'.format(link_name+"_joint"),
        '\t\t<parent link="{}"/>'.format(parent_link),
        '\t\t<child link="{}"/>'.format(link_name),
        '\t\t<origin rpy="0 0 0" xyz="{} {} {}"/>'.format(*joint_origin),
        '\t</joint>\n\n'
    ])

def generate_fixed_joint_link(link_name, joint_name, parent_link, joint_origin):
    return "\n".join([
        '\t<link name="{}"/>\n'.format(link_name),
        '\t<joint name="{}" type="fixed">'.format(joint_name),
		'\t\t<parent link="{}"/>'.format(parent_link),
		'\t\t<child link="{}"/>'.format(link_name),
		'\t\t<origin rpy="{} {} {}" xyz="{} {} {}"/>'.format(*joint_origin),
	    '\t</joint>\n\n'
    ])

# Contact surface string generating function
def generate_contact_surface(parent_link, surface):
    return "\n".join([
        '\t<planar_surface name="{}" link="{}">'.format(surface, parent_link),
        '\t\t<origin xyz="0 0 0 " rpy="0 0 0" />',
        '\t\t<points>',
        '\t\t\t<point xy="0 0" />',
        '\t\t</points>',
        '\t\t<material name="plastic" />',
        '\t</planar_surface>\n\n',
    ])

